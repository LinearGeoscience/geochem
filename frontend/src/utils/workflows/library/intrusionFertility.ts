/** Scott Halley: fertile intrusions for porphyry Cu and Archean Au (Yilgarn granite project, IAGS 2024 workshop). */
import { el, ox, xy, diag, rules, rule, w, calcRatio, calcAction, step, cite, workflow, ratio, level, calc, SILICA, CALC_V_SC, CALC_SR_Y, CALC_ZR_HF, CALC_EU, DIAGRAM } from './builders';

export const intrusionFertility = workflow({
    id: 'intrusion-fertility',
    name: 'Intrusion fertility (porphyry Cu, Au centres)',
    group: 'Porphyry & epithermal',
    summary: 'Sr/Y, V/Sc, Eu*, Zr/Hf: hydrous oxidised magma or not. Works with 4-acid data (Sc instead of SiO2).',
    steps: [
        step('sr-y', 'Sr/Y: hornblende suite',
            'Sr/Y >40 marks the hornblende diorite / porphyry suite (titanite fractionation, plagioclase suppressed). Only where alteration has not removed Sr.',
            'Sr/Th vs Th and Sr/Nb vs Nb should look like Sr/Y vs Y; if not, Sr was mobile.',
            [CALC_SR_Y, calcRatio('Sr/Th', el('Sr'), el('Th')), calcRatio('Sr/Nb', el('Sr'), el('Nb')),
                diag(DIAGRAM.srYVsY),
                xy(SILICA, [calc('Sr/Y')], { refLines: [level(calc('Sr/Y'), 40, 'Sr/Y = 40')] }),
                xy(el('Th'), [calc('Sr/Th')], { log: 'xy' }), xy(el('Nb'), [calc('Sr/Nb')], { log: 'xy' })]),
        step('v-sc', 'V/Sc: hornblende before magnetite',
            'V/Sc rising with silica = hornblende crystallised first in a hydrous, oxidised magma (Loucks 2014). Falling V/Sc = magnetite fractionation, not porphyry.',
            'Background V/Sc 7–8; porphyry magmas Sc 4–8 ppm with V/Sc 10–15.',
            [CALC_V_SC, diag(DIAGRAM.vScVsSc), xy(SILICA, [calc('V/Sc')])]),
        step('eu', 'Eu*: plagioclase held back',
            'Eu/Eu* >0.8 with Sr/Y >25 means no plagioclase fractionation. Fractionated rhyolite has low Eu*.',
            'Points above the 0.8 line at 62–70 % SiO2.',
            [CALC_EU, xy(SILICA, [calc('Eu/Eu*')], { refLines: [level(calc('Eu/Eu*'), 0.8, 'Eu* = 0.8')] })]),
        step('zr-hf', 'Zr/Hf: zircon or alkalic',
            'Crustal Zr/Hf ≈ 36. Below 30 above 70 % SiO2 = zircon fractionation (fractionated potassic granite); 40–55 = alkalic (baddeleyite), e.g. Wallaby, Tropicana.',
            'Granites off the 36 line: which side, and at what silica.',
            [CALC_ZR_HF, xy(el('Hf'), [el('Zr')], { refLines: [ratio(el('Zr'), el('Hf'), 36, { label: 'Zr/Hf = 36' })] }),
                xy(SILICA, [calc('Zr/Hf')], { refLines: [level(calc('Zr/Hf'), 30, 'Zr/Hf = 30'), level(calc('Zr/Hf'), 40, 'Zr/Hf = 40')] })]),
        step('titanite', 'Titanite: Ti and Nb together',
            'Titanite takes Ti and Nb so both fall towards the origin. Porphyry magmas: Ti 1000–4000, Nb 2–6, Th 2–4, Y 5–10, Ce 20–50 ppm.',
            'A trend to the origin on Ti vs Nb at low Y.',
            [xy(el('Nb'), [el('Ti'), el('Y')], { log: 'xy' })]),
        step('alkalinity', 'Alkalinity and Ba',
            'Alkalic suites have high Sr and high Y, high V/Sc, P, Ti, Th and LREE. Ba >1000 ppm is the sulphur / fertility proxy in hornblende diorites and alkalic intrusions.',
            'Alkalinity index rising with silica; Ba above 1000 ppm.',
            [calcAction('Alkalinity index', '(A/22.990+B/39.098)/(C/40.078+A/22.990+B/39.098)', { A: el('Na'), B: el('K'), C: el('Ca') }, ['AI molar', '(Na+K)/(Ca+Na+K)']),
                xy(SILICA, [calc('Alkalinity index'), el('Ba')])]),
        step('granite-groups', 'Granite groups (Yilgarn)',
            'Halley\'s reclassification: Alkalic (Zr/Hf >40), Fractionated potassic (SiO2 >70 % and Zr/Hf <30), Hornblende diorite (Sr/Y >40), Potassic granite (Sr/Y <40). Review the sheet, then Apply.',
            'Gold camps sit on hydrous diorite or alkalic centres; Bi–Te ± Mo footprint around them.',
            [CALC_SR_Y, CALC_ZR_HF,
                rules('Yilgarn granite groups (Halley 2021)', [
                    rule('Alkalic suite', '#8e24aa', [w(calc('Zr/Hf'), 40)]),
                    rule('Fractionated potassic granite', '#e53935', [w(ox('SiO2'), 70), w(calc('Zr/Hf'), undefined, 30)]),
                    rule('Hornblende diorite', '#d81b60', [w(calc('Sr/Y'), 40)]),
                    rule('Potassic granite', '#fb8c00', [w(calc('Sr/Y'), undefined, 40)]),
                ])]),
    ],
    references: [
        cite('Halley, S. (2021) Archean granite chemistry, Yilgarn; (2024) Rock compositions from assays, IAGS workshop.'),
        cite('Loucks, R.R. (2014) Distinctive composition of copper-ore-forming arc magmas. Australian Journal of Earth Sciences 61, 5–16.'),
        cite('Richards, J.P. (2011) High Sr/Y arc magmas and porphyry Cu ± Mo ± Au deposits: just add water. Economic Geology 106, 1075–1081.'),
    ],
});
