/** Scott Halley: porphyry Cu alteration from major elements (Porphyry Cu Geochemistry Module 2). */
import { el, xy, diag, cum, box, rules, rule, w, map, pathfinder, step, cite, workflow, ratio, calc, PYRITE, CALCITE, DOLOMITE, CALC_K_AL, CALC_NA_AL, DIAGRAM } from './builders';

export const porphyryAlteration = workflow({
    id: 'porphyry-alteration',
    name: 'Porphyry Cu alteration',
    group: 'Porphyry & epithermal',
    summary: 'K/Al–Na/Al, Al-K-Mg, Ca-Fe-S, Fe–S and K–Rb: sericite, chlorite–biotite, anhydrite, sulphidation and alunite, then grade by zone.',
    steps: [
        step('white-mica', 'White mica vs feldspar',
            'K/Al vs Na/Al (molar) with the feldspar and mica nodes. Points above the muscovite–albite tie-line need K-feldspar or biotite.',
            'Where the data sit between albite, K-feldspar, muscovite and paragonite.',
            [diag(DIAGRAM.feldsparNaK, ['ab', 'kf', 'mu', 'pg', 'tie:mu|ab'])]),
        step('al-k-mg', 'Sericite, chlorite, biotite and anhydrite',
            'Al-K-Mg: K side of the chlorite–muscovite join = K-feldspar or biotite; on the K–Al join past muscovite = advanced argillic. Ca-Fe-S: S pulls points to the anhydrite–pyrite tie-line.',
            'Least-altered rocks mid-way on Ca–Fe; the anhydrite dissolution front; S-rich side of pyrite = alunite or chalcocite.',
            [diag(DIAGRAM.alKMg, ['mu', 'kf', 'chl', 'bt']), diag(DIAGRAM.caFeS, ['anh', 'py', 'tie:anh|py'])]),
        step('fe-s-carbonate', 'Sulphidation and carbonate',
            'Fe vs S against the pyrite line shows how much Fe is sulphidised. Ca vs Mg separates calcite from dolomite; Ca vs C against the calcite line.',
            'Points on the pyrite line = all Fe in pyrite; Ca without C = anhydrite or feldspar.',
            [xy(el('Fe'), [el('S')], { refLines: [PYRITE] }), xy(el('Ca'), [el('Mg'), el('C')], { refLines: [DOLOMITE, CALCITE] })]),
        step('alunite', 'Alunite: K without Rb',
            'K/Rb ≈ 250 in igneous rocks and micas. Alunite takes K but not Rb, so K rises off the line.',
            'Points above the K/Rb = 250 line at low Rb.',
            [xy(el('Rb'), [el('K')], { refLines: [ratio(el('K'), el('Rb'), 250, { label: 'K/Rb = 250' })] })]),
        step('zones', 'Alteration zones by rule',
            'Module 2 cut-offs on K/Al, Na/Al (molar), Mg and S. First match wins; review and edit the sheet, then Apply.',
            'Feldspar–sulphide–sulphate is the commonest porphyry assemblage; argillic never strips all the Mg, Na and Ca.',
            [CALC_K_AL, CALC_NA_AL,
                rules('Porphyry alteration (Halley Module 2)', [
                    rule('Alunite', '#f06292', [w(calc('K/Al molar'), undefined, 0.3), w(calc('Na/Al molar'), undefined, 0.05), w(el('S'), 10000)]),
                    rule('Advanced argillic', '#ba68c8', [w(calc('Na/Al molar'), undefined, 0.05), w(calc('K/Al molar'), undefined, 0.25), w(el('Mg'), undefined, 1000)]),
                    rule('Sericite-chlorite', '#4db6ac', [w(calc('Na/Al molar'), undefined, 0.05), w(calc('K/Al molar'), 0.25, 0.33), w(el('Mg'), 10000)]),
                    rule('Sericite (intense phyllic)', '#ffb300', [w(calc('Na/Al molar'), undefined, 0.05), w(calc('K/Al molar'), 0.25, 0.4)]),
                    rule('Potassic', '#e53935', [w(calc('K/Al molar'), 0.5)]),
                    rule('Moderate phyllic', '#fdd835', [w(calc('Na/Al molar'), 0.05, 0.25), w(calc('K/Al molar'), 0.25, 0.5)]),
                    rule('Feldspar-sulphide-sulphate', '#9e9d24', [w(calc('Na/Al molar'), 0.25), w(el('S'), 5000)]),
                    rule('Unaltered', '#90a4ae', [w(calc('Na/Al molar'), 0.25), w(el('S'), undefined, 5000)]),
                ])]),
        step('grade', 'Grade by zone',
            'Split cumulative frequency of Cu, Mo and Au by alteration group, then the pathfinders against the upper crust. Drop ICP-AES rows for Bi, Te and Sb (high detection limits).',
            'Which zone carries the Cu; Cu–Mo–Bi–Te–As–Cs–Li zoning outward.',
            [cum([el('Cu'), el('Mo'), el('Au')])]),
        step('pathfinders', 'Pathfinders vs crust',
            'Box plots of the pathfinders by group against the upper-crust line. A coherent group >10× crust is a significant anomaly.',
            'Bi and Te with the Cu zone; As, Sb, Cs and Li outboard.',
            [box([el('Bi'), el('Te'), el('As'), el('Sb'), el('Cs'), el('Li'), el('Mo'), el('W')])]),
        step('space', 'Zoning in space',
            'Groups on the map and anomaly multiples on the pathfinder map.',
            'Concentric zoning around the Cu centre.',
            [map(), pathfinder(['Mo', 'Bi', 'Te', 'As', 'Sb', 'Cs', 'Li'])]),
    ],
    references: [
        cite('Halley, S. Porphyry Cu geochemistry, Modules 1–2 (tutorials).'),
        cite('Halley, S., Dilles, J.H. & Tosdal, R.M. (2015) Footprints: hydrothermal alteration and geochemical dispersion around porphyry copper deposits. SEG Newsletter 100.'),
    ],
});
