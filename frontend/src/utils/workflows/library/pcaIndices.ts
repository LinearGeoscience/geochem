/** PCA on CLR data, then additive indices from the element associations at each PC end. */
import { el, cum, analysis, dialog, pcaResults, indices, step, cite, workflow, TAB } from './builders';

export const pcaIndices = workflow({
    id: 'pca-indices',
    name: 'PCA → multi-element indices',
    group: 'Basics',
    summary: 'Clean the below-detection data, split by assay protocol, run CLR PCA on one protocol, then map additive indices of the associations it finds.',
    steps: [
        step('bdl', 'Below-detection format',
            'BDL supplied as ½ the detection limit reads as a real value and makes a false population. Convert such columns to <DL (stored as −DL).',
            'Data Doctor rows for "½ detection limit as a value"; a high-confidence row has an empty gap below the limit.',
            [dialog('dataDoctor')]),
        step('protocols', 'Assay protocols',
            'Samples analysed for another element suite or with other detection limits must be treated apart. Choose the batch / lab method column if there is one; with mixed sample media set "Within" to the medium column (soil and rock never share a group). Then Add column. Show the split opens the limits-by-group chart, a map and probability plots coloured by group; Add to report writes the method, the group table and those figures.',
            'Groups that differ in element count or DL (Chart tab: blank = not analysed, colour = DL vs the lowest); mixed-DL warnings inside a group.',
            [dialog('assayProtocols')]),
        step('split-prob', 'Probability plots by protocol',
            'Colour by the protocol column first. Each protocol should show its own detection-limit step; populations that only appear in one protocol are method artefacts.',
            'Curves that coincide above the detection limits; breaks that repeat in every protocol.',
            [cum([el('Cu'), el('Pb'), el('Zn'), el('Ag'), el('Au'), el('As'), el('Sb'), el('Bi'), el('Mo'), el('W'), el('S'), el('Ba')])]),
        step('pca', 'CLR PCA on one protocol',
            'In Assay protocols use "Use only" on the largest low-DL group, then run PCA with the CLR transform and "Use filtered data".',
            'Scree plot: the components before the curve flattens carry the structure.',
            [analysis(TAB.pca)]),
        step('eigen', 'Ranked eigenvectors',
            'Read the elements loading together at each end of each PC. Select an end group and press Build Index (sum of CLR values).',
            'Elements that sit apart from the main cluster at one end of a PC, repeated on more than one PC.',
            [pcaResults]),
        step('index-prob', 'Index distributions',
            'An index separates a background population from an upper tail better than any of its elements alone.',
            'A break in slope near the top of each index curve; compare it between colour groups.',
            [indices('probability')]),
        step('index-xy', 'Index against index',
            'Two indices plotted together show whether their signatures coincide, zone around each other or are unrelated.',
            'Samples high in one index and not the other; a shared high corner.',
            [indices('scatter')]),
        step('index-map', 'Index map',
            'Map the first index by quantile; repeat for the others with Colour by on the Build Index result.',
            'Coherent clusters and trends of the top quantiles rather than single samples.',
            [indices('map')]),
    ],
    references: [
        cite('Aitchison, J. (1986) The Statistical Analysis of Compositional Data. Chapman & Hall.'),
        cite('Grunsky, E.C. (2010) The interpretation of geochemical survey data. Geochemistry: Exploration, Environment, Analysis 10, 27–74.'),
    ],
});
