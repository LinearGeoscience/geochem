/** Intrusion-hosted Ni-Cu-Co-PGE: sulphide first, S/Se, olivine vs sulphide Ni, PGE vs Cu (Barnes 1990, Karykowski 2017), mantle-normalised metals, tenor. */
import { el, xy, diag, cum, box, spider, map, pathfinder, calcRatio, calcAction, analysis, step, cite, workflow, ratio, calc, CALC_MG_NUMBER, DIAGRAM, TAB } from './builders';

export const niCuPgeIntrusion = workflow({
    id: 'ni-cu-pge-intrusion',
    name: 'Intrusion-hosted Ni-Cu-Co-PGE',
    group: 'Nickel & PGE',
    summary: 'Where the sulphide is, whether its S is mantle or crustal, olivine vs sulphide Ni, PGE vs Cu, mantle-normalised metals, tenor.',
    steps: [
        step('sulphide', 'Where is the sulphide',
            'Split cumulative frequency of S, Ni, Cu, Co, Pt, Pd by group; S against Ni, Cu, Co on log axes.',
            'Metals rising with S = sulphide-hosted; metals without S = silicate (olivine) Ni.',
            [cum([el('S'), el('Ni'), el('Cu'), el('Co'), el('Pt'), el('Pd')]), xy(el('S'), [el('Ni'), el('Cu'), el('Co')], { log: 'xy' })]),
        step('s-se', 'S/Se: mantle or crustal sulphur',
            'Mantle sulphide has S/Se ≈ 2600–4400. Well above 5000 = crustal S added (contamination, external sulphur); below 2000 = S lost.',
            'Where the sulphide-rich groups sit relative to the 3000 line.',
            [calcRatio('S/Se', el('S'), el('Se'), ['S_Se']),
                xy(el('Se'), [el('S')], { log: 'xy', refLines: [ratio(el('S'), el('Se'), 3000, { label: 'S/Se = 3000 (mantle)' })] })]),
        step('olivine', 'Olivine Ni vs sulphide Ni',
            'MgO vs Ni with the barren-komatiite olivine field; Mg# against Ni and Cr.',
            'Ni above the olivine field = sulphide; cumulates track Mg#.',
            [CALC_MG_NUMBER, diag(DIAGRAM.barrenKomatiite), xy(calc('Mg#'), [el('Ni'), el('Cr')], { log: 'y' })]),
        step('pge-cu', 'PGE vs Cu',
            'Cu/Pd vs Pd (Karykowski 2017): PGE-depleted vs undepleted sulphide. Pd/Ir and Pd/Pt vs Ni/Cu (Barnes 1990) place the sulphide type.',
            'Cu/Pd above the mantle range = sulphide already segregated upstream (PGE depleted).',
            [calcAction('Cu/Pd (ppm/ppb)', 'A/(B*1000)', { A: el('Cu'), B: el('Pd') }, ['Cu/Pd', 'Cu_Pd']),
                diag(DIAGRAM.cuPdVsPd), diag(DIAGRAM.pdIrVsNiCu), diag(DIAGRAM.pdPtVsNiCu)]),
        step('mantle-norm', 'Mantle-normalised metals',
            'Ni–Os–Ir–Ru–Rh–Pt–Pd–Au–Cu normalised to primitive mantle, group means.',
            'Flat = undepleted mantle sulphide; IPGE-depleted or Pt–Pd-enriched patterns by group.',
            [spider([el('Ni'), el('Os'), el('Ir'), el('Ru'), el('Rh'), el('Pt'), el('Pd'), el('Au'), el('Cu')], 'primitive-mantle-sm95', 'groups')]),
        step('tenor', 'Tenor',
            'Analysis › Recalculation (Barnes 2023), mafic-cumulate suite: Ni in 100 % sulphide.',
            'Ni_Tenor by group; compare with the Pd/Ir and Cu/Pd groups.',
            [analysis(TAB.recalculation)]),
        step('metals-vs-crust', 'Metals vs crust',
            'Box plots of Ni, Cu, Co, Pt, Pd, Te, Se, Bi, As by group against the upper-crust line; Co vs Ni and Cu vs Ni with the 1:1 line.',
            'Co/Ni and Ni/Cu of the sulphide groups.',
            [box([el('Ni'), el('Cu'), el('Co'), el('Pt'), el('Pd'), el('Te'), el('Se'), el('Bi'), el('As')])]),
        step('ratios', 'Co/Ni and Ni/Cu',
            'Co vs Ni and Cu vs Ni on log axes with the 1:1 line.',
            'Ni/Cu >1 for olivine-rich sulphide; Cu-rich sulphide near 1 or below.',
            [xy(el('Ni'), [el('Co'), el('Cu')], { log: 'xy', refLines: [ratio(el('Cu'), el('Ni'), 1, { label: 'Ni/Cu = 1' })] })]),
        step('space', 'In space',
            'Groups on the map; Pd, Pt, Cu, Ni, Te, Se multiples on the pathfinder map (Extended mode).',
            'Sulphide groups along the intrusion contact or feeder.',
            [map(), pathfinder(['Pd', 'Pt', 'Cu', 'Ni', 'Te', 'Se'])]),
    ],
    references: [
        cite('Barnes, S.-J. (1990) The use of metal ratios in prospecting for platinum-group element deposits in mafic and ultramafic intrusions. J. Geochem. Explor. 37, 91–99.'),
        cite('Karykowski, B.T. et al. (2017) Cu/Pd ratios as a PGE-depletion index (Monchegorsk / Fennoscandia).'),
        cite('Eckstrand, O.R. & Hulbert, L.J. (1987) Selenium and the source of sulfur in magmatic nickel and platinum deposits. GAC-MAC Abstracts 12.'),
        cite('Naldrett, A.J. (2004) Magmatic Sulfide Deposits. Springer.'),
    ],
});
