/** Komatiite-hosted Ni: Barnes (2004) diagrams, Halley's Sc–Cr trend, Al-depletion, chalcophile depletion, tenor. */
import { el, ox, xy, diag, box, calcRatio, analysis, step, cite, workflow, ratio, level, calc, DIAGRAM, TAB } from './builders';

export const komatiiteNi = workflow({
    id: 'komatiite-ni',
    name: 'Komatiite Ni',
    group: 'Nickel & PGE',
    summary: 'Classify, test olivine control, read Ni depletion and facies (Barnes 2004), then S, Se and PGE by group and tenor.',
    steps: [
        step('classify', 'Classify the ultramafics',
            'Jensen (Kalgoorlie MUM) and MgO vs FeO (Barnes 2004) place the samples: komatiite, komatiitic basalt, cumulate.',
            'Komatiite field; cumulates at high MgO.',
            [diag(DIAGRAM.jensenKalgoorlie), diag(DIAGRAM.komatiiteMgOFeO)]),
        step('olivine', 'Olivine control and Ni depletion',
            'Komatiites follow one Sc–Cr olivine trend. On MgO vs Ni, barren komatiites sit in the olivine-control field; Ni below it was taken by sulphide.',
            'Points below the barren field = Ni-depleted (sulphide segregated nearby).',
            [diag(DIAGRAM.komatiiteScCr), diag(DIAGRAM.barrenKomatiite)]),
        step('facies', 'Flow facies',
            'Ni/Cr vs Ni/Ti (Barnes 2004, all facies) separates channel, sheet flow, thin spinifex flow and sill facies.',
            'Channelised sheet flows and dunitic channels host the ore.',
            [diag(DIAGRAM.komatiiteFacies)]),
        step('al-ti', 'Al-depleted or undepleted',
            'Al2O3/TiO2 ≈ 20 (chondritic) = Al-undepleted (Munro type); ≈ 10 = Al-depleted (Barberton type).',
            'Which komatiite type, and whether it changes along strike.',
            [calcRatio('Al2O3/TiO2', ox('Al2O3'), ox('TiO2'), ['Al2O3_TiO2']),
                xy(ox('MgO'), [calc('Al2O3/TiO2')], { refLines: [level(calc('Al2O3/TiO2'), 10, 'Al-depleted ≈ 10'), level(calc('Al2O3/TiO2'), 20, 'Chondritic ≈ 20')] })]),
        step('chalcophile', 'Chalcophile depletion',
            'Against Fe the transition metals rise and Mg falls. Cu, Pd and Pt falling off the olivine trend = stripped by sulphide.',
            'Komatiites depleted in Cu–Pd–Pt relative to their MgO.',
            [xy(el('Fe'), [el('Mg'), el('Sc'), el('Cr'), el('Cu'), el('Zn'), el('Mn')]), xy(ox('MgO'), [el('Cu'), el('Pd'), el('Pt')], { log: 'y' })]),
        step('sulphide', 'Sulphide: S, Se and the metals',
            'S vs Ni and Cu; Se vs S around the mantle S/Se (≈ 3000). Box plots of Ni, Cu, Co, Pt, Pd, S, Se by group against the crust.',
            'S/Se well above 3000 = crustal S added; sulphide-rich groups with PGE.',
            [calcRatio('S/Se', el('S'), el('Se'), ['S_Se']),
                xy(el('S'), [el('Ni'), el('Cu')], { log: 'xy' }), xy(el('Se'), [el('S')], { log: 'xy', refLines: [ratio(el('S'), el('Se'), 3000, { label: 'S/Se = 3000 (mantle)' })] })]),
        step('metals-vs-crust', 'Metals vs crust',
            'Box plots by group against the upper-crust line.',
            'Groups with Ni, Cu, Pt and Pd well above crust and above their olivine control.',
            [box([el('Ni'), el('Cu'), el('Co'), el('Pt'), el('Pd'), el('S'), el('Se')])]),
        step('tenor', 'Tenor',
            'Analysis › Recalculation (Barnes 2023): anhydrous, sulphide-corrected Ni tenor for the komatiite suite.',
            'Ni_Tenor and Ni_Sulfide columns; compare tenor by group afterwards.',
            [analysis(TAB.recalculation)]),
    ],
    references: [
        cite('Barnes, S.J. et al. (2004) Komatiites and nickel sulfide ores of the Black Swan area, Yilgarn Craton. Mineralium Deposita 39.'),
        cite('Halley, S. (2021) Kalgoorlie komatiite Sc vs Cr; Barcode workshop.'),
        cite('Nesbitt, R.W., Sun, S.-S. & Purvis, A.C. (1979) Komatiites: geochemistry and genesis. Canadian Mineralogist 17, 165–186.'),
        cite('Barnes, S.J. (2023) Recalculation of whole-rock Ni-Cu-Co data (Barnes recalculation).'),
    ],
});
