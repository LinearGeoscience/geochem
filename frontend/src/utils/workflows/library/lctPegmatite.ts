/** LCT pegmatite lithium: fractionation ratios (K/Rb, Nb/Ta, Zr/Hf, Rb/Sr, Mg/Li) and the Li-Cs-Ta-Be-Sn suite against the crust. */
import { el, xy, cum, box, map, pathfinder, step, cite, workflow, ratio, calc, CALC_ZR_HF } from './builders';

export const lctPegmatite = workflow({
    id: 'lct-pegmatite',
    name: 'Lithium (LCT pegmatite)',
    group: 'Lithium',
    summary: 'Li distribution, then K/Rb, Nb/Ta, Zr/Hf, Rb/Sr, Mg/Li fractionation lines and the Li-Cs-Ta-Be-Sn suite vs crust.',
    steps: [
        step('li', 'Li distribution',
            'Li (from Li2O when that is what was assayed) with Cs, Ta and Rb: split cumulative frequency by group and Li against each on log axes.',
            'A Li population well above the host; Cs and Ta rising with it.',
            [cum([el('Li'), el('Cs'), el('Ta'), el('Rb')]), xy(el('Li'), [el('Cs'), el('Rb'), el('Ta')], { log: 'xy' })]),
        step('k-rb', 'K/Rb: fractionation',
            'K/Rb ≈ 250 in ordinary igneous rocks (Halley). Rb rises with fractionation: fertile LCT granites and pegmatites fall well below the line (K/Rb <150, Selway et al. 2005).',
            'Points below the 250 line and how far; a trend to K/Rb <150.',
            [xy(el('Rb'), [el('K')], { log: 'xy', refLines: [ratio(el('K'), el('Rb'), 250, { label: 'K/Rb = 250' }), ratio(el('K'), el('Rb'), 150, { label: 'K/Rb = 150 (fertile)' })] })]),
        step('nb-ta', 'Nb/Ta',
            'Upper crust Nb/Ta ≈ 12. Nb/Ta <5 marks mineralised peraluminous granites (Ballouard et al. 2016); Ta rises with fractionation.',
            'Points below the Nb/Ta = 5 line.',
            [xy(el('Ta'), [el('Nb')], { log: 'xy', refLines: [ratio(el('Nb'), el('Ta'), 12, { label: 'Nb/Ta = 12 (UCC)' }), ratio(el('Nb'), el('Ta'), 5, { label: 'Nb/Ta = 5' })] })]),
        step('zr-hf', 'Zr/Hf',
            'Crustal Zr/Hf ≈ 36; zircon fractionation pulls it below 30 in evolved granites.',
            'Low Zr/Hf with high Rb = the fractionated end.',
            [CALC_ZR_HF, xy(el('Hf'), [el('Zr')], { log: 'xy', refLines: [ratio(el('Zr'), el('Hf'), 36, { label: 'Zr/Hf = 36' })] }), xy(el('Rb'), [calc('Zr/Hf')], { log: 'x' })]),
        step('rb-sr-mg-li', 'Rb/Sr and Mg/Li',
            'Sr falls and Rb rises with fractionation; Li in mica follows Rb, Li in chlorite follows Mg. Pegmatite trends to low Mg/Li.',
            'High Rb/Sr with low Mg/Li = pegmatite; high Mg with Li = chlorite/host.',
            [xy(el('Sr'), [el('Rb')], { log: 'xy' }), xy(el('Mg'), [el('Li')], { log: 'xy' })]),
        step('suite-vs-crust', 'LCT suite vs crust',
            'Box plots of Li, Cs, Ta, Rb, Nb, Be, Sn, Ga, W by group against the upper-crust line. A coherent group >10× crust is significant.',
            'Which groups carry the full Li–Cs–Ta–Be–Sn suite, not just Li.',
            [box([el('Li'), el('Cs'), el('Ta'), el('Rb'), el('Nb'), el('Be'), el('Sn'), el('Ga'), el('W')])]),
        step('space', 'In space',
            'Groups on the map; Li, Cs, Sn, Ta multiples on the pathfinder map.',
            'Cs and Sn halos around the pegmatite swarm.',
            [map(), pathfinder(['Li', 'Cs', 'Sn', 'Ta'])]),
    ],
    references: [
        cite('Selway, J.B., Breaks, F.W. & Tindle, A.G. (2005) A review of rare-element (Li-Cs-Ta) pegmatite exploration techniques for the Superior Province. Exploration and Mining Geology 14, 1–30.'),
        cite('Ballouard, C. et al. (2016) Nb-Ta fractionation in peraluminous granites: a marker of the magmatic-hydrothermal transition. Geology 44, 231–234.'),
        cite('Halley, S. (2021) Archean granite chemistry: K/Rb and Rb/K with fractionation.'),
    ],
});
